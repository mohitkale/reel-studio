/**
 * Embed HyperFrames catalog HTML files as a TypeScript module so both the
 * client preview and the server render path can personalize blocks without fs.
 *
 * Usage: node scripts/embed-hf-catalog.mjs
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const blocksDir = path.join(root, "src/engines/hyperframes/catalog/blocks");
const outFile = path.join(root, "src/engines/hyperframes/catalog/html.ts");

function toExportName(file) {
  return file
    .replace(/\.html$/i, "")
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase())
    .replace(/[^a-zA-Z0-9]/g, "")
    .replace(/^(.)/, (c) => c.toLowerCase());
}

async function main() {
  const files = (await fs.readdir(blocksDir))
    .filter((f) => f.endsWith(".html"))
    .sort();
  if (files.length === 0) {
    throw new Error(`No HTML blocks in ${blocksDir}`);
  }

  const entries = [];
  const mapLines = [];

  for (const file of files) {
    const raw = await fs.readFile(path.join(blocksDir, file), "utf8");
    const id = file.replace(/\.html$/i, "");
    const exportName = `${toExportName(file)}Html`;
    entries.push(
      `export const ${exportName} = ${JSON.stringify(raw)} as string;\n`,
    );
    mapLines.push(`  ${JSON.stringify(id)}: ${exportName},`);
  }

  const banner = `/**
 * AUTO-GENERATED by scripts/embed-hf-catalog.mjs — do not edit by hand.
 * Re-run after updating files in catalog/blocks/.
 */

`;

  const body = `${banner}${entries.join("\n")}
export const HF_CATALOG_HTML: Record<string, string> = {
${mapLines.join("\n")}
};
`;

  await fs.writeFile(outFile, body, "utf8");
  console.log(`Wrote ${outFile} (${files.length} blocks)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
