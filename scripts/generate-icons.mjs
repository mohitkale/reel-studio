const root = path.resolve("node_modules/lucide-react/dist/esm/icons");
const out = {};
for (const name of NAMES) {
  const file = path.join(root, `${name}.mjs`);
  let text = "";
  try {
    text = readFileSync(file, "utf8");
  } catch {
    console.error(`missing icon: ${name}`);
    continue;
  }
  const start = text.indexOf("node: [");
  if (start < 0) {
    console.error(`unreadable icon: ${name}`);
    continue;
  }
  // Take the bracketed array that follows "node:" and stop at its match.
  let depth = 0;
  let end = start + 6;
  for (; end < text.length; end++) {
    if (text[end] === "[") depth++;
    else if (text[end] === "]" && --depth === 0) break;
  }
  const node = new Function(`return ${text.slice(start + 6, end + 1)}`)();
  out[name] = node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  "src/engines/hyperframes/assets/lucide-icons.generated.ts",
  `// Generated by scripts/generate-icons.mjs from lucide-react (ISC). Do not edit.\nexport const LUCIDE_ICONS: Readonly<Record<string, string>> = {\n${body}\n};\n`,
);
